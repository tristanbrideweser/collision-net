# Quick smoke-test
# ──────────────────────────────────────────────

if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--model",  required=True, help="Path to collision_model.pt")
    ap.add_argument("--n-configs", type=int, default=1000,
                    help="Number of random configs to test (throughput benchmark)")
    args = ap.parse_args()

    # Fake point cloud (replace with your real scene cloud)
    rng    = np.random.default_rng(0)
    fake_pc = rng.uniform(-1, 1, (2048, 3)).astype(np.float32)

    checker = NeuralCollisionChecker(
        model_path=args.model,
        scene_point_cloud=fake_pc,
    )

    # Single-config API
    cfg = rng.uniform(_JOINT_LOWER, _JOINT_UPPER, 7).astype(np.float32)
    print(f"\nSingle config collision: {checker.in_collision(cfg)}")
    print(f"Collision probability : {checker.collision_probability(cfg):.4f}")

    # Batch API + throughput
    configs = rng.uniform(_JOINT_LOWER, _JOINT_UPPER, (args.n_configs, 7)).astype(np.float32)

    import time
    t0   = time.time()
    mask = checker.batch_in_collision(configs)
    dt   = time.time() - t0

    print(f"\nBatch of {args.n_configs} configs:")
    print(f"  Predicted collisions : {mask.sum()} ({mask.mean()*100:.1f}%)")
    print(f"  Elapsed              : {dt*1000:.1f} ms")
    print(f"  Throughput           : {args.n_configs/dt:,.0f} configs/s")
